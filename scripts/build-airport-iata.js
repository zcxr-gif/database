'use strict';

/*
 * data/airport-iata.json: IATA -> ICAO, so a route spreadsheet written in
 * three-letter codes ("AUH", "JFK") imports as the four-letter codes the crew
 * center works in.
 *
 * Built from the tracker's airports-core.json (OurAirports, public domain),
 * which is keyed by ICAO and carries each airport's IATA code and a size class
 * `s` (4 = large). Where two airports claim one IATA code, the larger wins.
 *
 *   node scripts/build-airport-iata.js ../tracker/airports-core.json
 */

const fs = require('fs');
const path = require('path');

const src = process.argv[2] || path.join(__dirname, '..', '..', 'tracker', 'airports-core.json');
const airports = JSON.parse(fs.readFileSync(src, 'utf8'));
const best = new Map();
for (const [icao, a] of Object.entries(airports)) {
    const iata = String((a && a.iata) || '').trim().toUpperCase();
    if (!/^[A-Z0-9]{3}$/.test(iata) || !/^[A-Z0-9]{4}$/.test(icao)) continue;
    const size = Number(a.s) || 0;
    const had = best.get(iata);
    if (!had || size > had.size) best.set(iata, { icao, size });
}
const out = { _comment: 'IATA -> ICAO. Generated by scripts/build-airport-iata.js from OurAirports data (public domain). Where two airports share an IATA code, the larger one wins.' };
for (const k of [...best.keys()].sort()) out[k] = best.get(k).icao;
const dest = path.join(__dirname, '..', 'data', 'airport-iata.json');
fs.writeFileSync(dest, JSON.stringify(out) + '\n');
console.log(`${best.size} codes -> ${path.relative(process.cwd(), dest)}`);
